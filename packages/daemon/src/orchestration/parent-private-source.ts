import { createHash } from 'node:crypto';
import { promisify } from 'node:util';
import { inflate } from 'node:zlib';
import { sha256 } from '../managed/canonical.js';
import { MAX_CANDIDATE_BYTES, managedGit } from '../managed/source-git.js';
import { type CandidatePathAllowance, validateCandidatePathScope } from './candidate-path-scope.js';
import { withVerifiedCheckpointMirror } from './local-checkpoints.js';

export interface ParentPrivateSourceSelector {
  /** Exact host-selected parent commit. */
  base: string;
  /** Exact exported HEAD commit. */
  commit: string;
  /** Exact tree expected at the exported HEAD. */
  tree: string;
  /** Host-owned authorization. Never derive this from worker output. */
  allowlist: readonly CandidatePathAllowance[];
  /** Host-selected collection bound, additionally capped by MAX_CANDIDATE_BYTES. */
  maxBundleBytes: number;
}

export interface VerifiedParentPrivateSource {
  base: string;
  commit: string;
  tree: string;
  bundle: Buffer;
  bundleDigest: string;
  paths: readonly string[];
}

// Initial private exporter contract: one SHA-1 HEAD, no prerequisites/deltas.
// Inspect expansion before invoking Git on untrusted bytes. The collector
// writes the exact bundle header above a pack generated by `pack-objects --revs
// --stdout --window=0 --no-reuse-object --no-reuse-delta --no-use-bitmap-index`,
// with only the resolved commit on stdin. `bundle create` may reuse packed deltas.
const inflateObject = promisify(inflate);
const maxExportObjects = 4096;
const maxExpansionMs = 30_000;

async function assertBoundedHeadPack(bundle: Buffer, commit: string) {
  if (!/^[a-f0-9]{40}$/.test(commit)) throw new Error('parent-private-source-pack-format');
  const header = Buffer.from(`# v2 git bundle\n${commit} HEAD\n\n`);
  const packEnd = bundle.length - 20;
  if (
    !bundle.subarray(0, header.length).equals(header) ||
    packEnd < header.length + 12 ||
    bundle.toString('ascii', header.length, header.length + 4) !== 'PACK' ||
    bundle.readUInt32BE(header.length + 4) !== 2 ||
    !createHash('sha1')
      .update(bundle.subarray(header.length, packEnd))
      .digest()
      .equals(bundle.subarray(packEnd))
  )
    throw new Error('parent-private-source-pack-format');
  const count = bundle.readUInt32BE(header.length + 8);
  if (!count || count > maxExportObjects) throw new Error('parent-private-source-object-limit');
  const deadline = performance.now() + maxExpansionMs;
  let offset = header.length + 12;
  let remaining = MAX_CANDIDATE_BYTES;
  for (let i = 0; i < count; i++) {
    let byte = bundle[offset++];
    if (byte === undefined || offset >= packEnd)
      throw new Error('parent-private-source-pack-format');
    const type = (byte >>> 4) & 7;
    if (type < 1 || type > 3) throw new Error('parent-private-source-object-type');
    let size = byte & 15;
    let shift = 4;
    while (byte & 128) {
      byte = bundle[offset++];
      if (byte === undefined || offset >= packEnd || shift > 25)
        throw new Error('parent-private-source-object-limit');
      size += (byte & 127) * 2 ** shift;
      shift += 7;
    }
    if (size > Math.min(remaining, 8 * 1024 * 1024))
      throw new Error('parent-private-source-object-limit');
    let result: { buffer: Buffer; engine: { bytesWritten: number } };
    try {
      // Node's asynchronous zlib work stays off the daemon event loop. Keep only
      // one expansion in flight; its compressed input and output are both bounded.
      result = (await inflateObject(bundle.subarray(offset, packEnd), {
        maxOutputLength: size + 1,
        info: true,
      })) as unknown as typeof result;
    } catch {
      throw new Error('parent-private-source-pack-format');
    }
    if (performance.now() >= deadline) throw new Error('parent-private-source-expansion-timeout');
    if (result.buffer.length !== size || !result.engine.bytesWritten)
      throw new Error('parent-private-source-pack-format');
    offset += result.engine.bytesWritten;
    remaining -= size;
  }
  if (offset !== packEnd) throw new Error('parent-private-source-pack-format');
}

/**
 * Host-only verification for bytes exported by a trusted isolated collection boundary.
 * The bundle is hostile data: this imports objects into a disposable mirror and never
 * consumes a remote, credential, checkout path, worker-selected path, or dirty worktree.
 */
export async function verifyParentPrivateSource(
  scratch: string,
  exportedHeadBundle: Buffer,
  input: Readonly<ParentPrivateSourceSelector>,
): Promise<VerifiedParentPrivateSource> {
  if (
    !Buffer.isBuffer(exportedHeadBundle) ||
    !Number.isSafeInteger(input.maxBundleBytes) ||
    input.maxBundleBytes < 1 ||
    input.maxBundleBytes > MAX_CANDIDATE_BYTES ||
    exportedHeadBundle.length < 1 ||
    exportedHeadBundle.length > input.maxBundleBytes
  )
    throw new Error('parent-private-source-bundle-size');

  // Bind all mutable boundary values before the first await. The allowlist remains
  // host authority, but is copied so a caller cannot change that authority in flight.
  const bundle = Buffer.from(exportedHeadBundle);
  const bundleDigest = sha256(bundle);
  const base = input.base;
  const commit = input.commit;
  const tree = input.tree;
  const allowlist = Array.isArray(input.allowlist)
    ? input.allowlist.map((entry) => ({ kind: entry.kind, path: entry.path }))
    : input.allowlist;

  await assertBoundedHeadPack(bundle, commit);
  const scoped = await withVerifiedCheckpointMirror(
    scratch,
    { predecessor: base, commit, tree },
    bundle,
    async (mirror) => {
      // A single advertised ref is insufficient: a pack may carry hidden objects.
      if (await managedGit(mirror, ['fsck', '--full', '--unreachable', '--no-reflogs', commit]))
        throw new Error('parent-private-source-unreachable-objects');
      return validateCandidatePathScope({
        repository: mirror,
        base,
        candidate: commit,
        expectedTree: tree,
        allowlist,
      });
    },
  );

  return {
    base: scoped.base,
    commit: scoped.candidate,
    tree: scoped.tree,
    bundle: Buffer.from(bundle),
    bundleDigest,
    paths: [...scoped.changedPaths],
  };
}
