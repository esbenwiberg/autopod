import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { canonicalConfiguration } from './canonical-configuration.js';

describe('canonicalConfiguration wire contract', () => {
  it('matches daemon-generated bytes, preserving arrays/nulls/floats/Unicode/escaping', () => {
    const vectors: { wire: string; canonical: string }[] = JSON.parse(
      readFileSync(
        new URL('../../desktop/Tests/Fixtures/configuration-digest-vectors.json', import.meta.url),
        'utf8',
      ),
    );
    for (const vector of vectors)
      expect(canonicalConfiguration(JSON.parse(vector.wire))).toBe(vector.canonical);
  });
  it('preserves historical omission semantics and primitive representations', () => {
    expect(canonicalConfiguration({ z: undefined, a: [null, false, 0, -0, 1.25] })).toBe(
      '{"a":[null,false,0,0,1.25]}',
    );
    expect(() => canonicalConfiguration(undefined)).toThrow('Undefined configuration value');
    expect(canonicalConfiguration('é')).not.toBe(canonicalConfiguration('e\u0301'));
    expect(canonicalConfiguration([1, 2])).not.toBe(canonicalConfiguration([2, 1]));
    expect(canonicalConfiguration(true)).not.toBe(canonicalConfiguration(1));
  });
});
